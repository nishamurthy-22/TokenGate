// Package metrics defines every Prometheus metric used by TokenGate in one place.
// See docs/DESIGN.md, section 9.
package metrics

import (
	"net/http"

	"github.com/prometheus/client_golang/prometheus"
	"github.com/prometheus/client_golang/prometheus/promauto"
	"github.com/prometheus/client_golang/prometheus/promhttp"
)

var (
	durationBuckets = []float64{0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10, 30, 60}
	ttftBuckets     = []float64{0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10}
	redisBuckets    = []float64{0.0005, 0.001, 0.0025, 0.005, 0.01, 0.025, 0.05, 0.1}
)

// Gateway metrics.
var (
	RequestsTotal = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "tg_requests_total",
		Help: "Requests handled by the gateway, by result status.",
	}, []string{"gateway_id", "app_id", "status"})

	TokensTotal = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "tg_tokens_total",
		Help: "Tokens by type: reserved, used, refunded, overshoot.",
	}, []string{"gateway_id", "app_id", "type"})

	RequestDuration = promauto.NewHistogramVec(prometheus.HistogramOpts{
		Name:    "tg_request_duration_seconds",
		Help:    "Total time to handle a request, including streaming.",
		Buckets: durationBuckets,
	}, []string{"gateway_id", "app_id", "backend"})

	TTFT = promauto.NewHistogramVec(prometheus.HistogramOpts{
		Name:    "tg_ttft_seconds",
		Help:    "Time from forwarding a request to receiving its first token.",
		Buckets: ttftBuckets,
	}, []string{"gateway_id", "backend"})

	RejectionsTotal = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "tg_rejections_total",
		Help: "Requests rejected by the gateway, by reason.",
	}, []string{"gateway_id", "app_id", "reason"})

	RetriesTotal = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "tg_retries_total",
		Help: "Retries sent to another backend after a failure.",
	}, []string{"gateway_id", "backend"})

	BackendOpenRequests = promauto.NewGaugeVec(prometheus.GaugeOpts{
		Name: "tg_backend_open_requests",
		Help: "Requests in flight from this gateway to each backend.",
	}, []string{"gateway_id", "backend"})

	BackendOutstandingTokens = promauto.NewGaugeVec(prometheus.GaugeOpts{
		Name: "tg_backend_outstanding_tokens",
		Help: "Reserved tokens in flight from this gateway to each backend.",
	}, []string{"gateway_id", "backend"})

	BackendHealthy = promauto.NewGaugeVec(prometheus.GaugeOpts{
		Name: "tg_backend_healthy",
		Help: "1 if the gateway considers the backend healthy, else 0.",
	}, []string{"gateway_id", "backend"})

	BreakerState = promauto.NewGaugeVec(prometheus.GaugeOpts{
		Name: "tg_breaker_state",
		Help: "Circuit breaker state: 0 closed, 1 half-open, 2 open.",
	}, []string{"gateway_id", "backend"})

	RedisLatency = promauto.NewHistogramVec(prometheus.HistogramOpts{
		Name:    "tg_redis_latency_seconds",
		Help:    "Latency of budget operations in Redis.",
		Buckets: redisBuckets,
	}, []string{"gateway_id", "op"})

	RedisErrorsTotal = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "tg_redis_errors_total",
		Help: "Failed budget operations in Redis.",
	}, []string{"gateway_id", "op"})
)

// Mock backend metrics.
var (
	MockActiveRequests = promauto.NewGaugeVec(prometheus.GaugeOpts{
		Name: "tg_mock_active_requests",
		Help: "Requests currently generating tokens.",
	}, []string{"backend"})

	MockQueueDepth = promauto.NewGaugeVec(prometheus.GaugeOpts{
		Name: "tg_mock_queue_depth",
		Help: "Requests waiting for a generation slot.",
	}, []string{"backend"})

	MockTokensGenerated = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "tg_mock_tokens_generated_total",
		Help: "Tokens generated by the mock backend.",
	}, []string{"backend"})

	MockRequestsTotal = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "tg_mock_requests_total",
		Help: "Requests handled by the mock backend, by result status.",
	}, []string{"backend", "status"})
)

// Handler serves all registered metrics for Prometheus.
func Handler() http.Handler {
	return promhttp.Handler()
}
